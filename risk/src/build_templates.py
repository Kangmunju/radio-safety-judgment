def main():
    with MASTER.open(encoding="utf-8-sig") as f:
        master = list(csv.DictReader(f))
    for name, (*_, (file, row, kw), _orig) in P.items():
        if not any(m["원본파일"] == file and m["원본행"] == row and kw in m["유해위험요인"] for m in master):
            raise SystemExit(f"틀 '{name}'의 바탕 원문 행이 없음: {file} {row}행")

    templates, steps = [], []
    for risk_id, (name, etype, part, task, task_word, body, gap) in enumerate(WORKS, 1):
        templates.append({"risk_id": risk_id, "work_name": name, "equipment_type": etype,
                          "part": part, "task": task, "gap_note": gap})
        words = {"설비": EQUIP_WORD[etype], "부품": part, "작업": task_word, "작업명": name}
        for step_no, key in enumerate(PREP + body + POST, 1):
            task_step, hclass, hazard, measure, (file, row, _), original = P[key]
            steps.append({"step_id": len(steps) + 1, "risk_id": risk_id, "step_no": step_no,
                          "hazard": hazard.format(**words), "countermeasure": measure.format(**words),
                          "task_step": task_step.format(**words), "hazard_class": hclass,
                          "likelihood": "", "severity": "", "risk_grade": "",
                          "source_file": file, "source_row": row,
                          "fit": "원문 그대로" if original else "단어 교체"})

    OUT.mkdir(parents=True, exist_ok=True)
    for fname, rows in (("risk_template.csv", templates), ("risk_step.csv", steps)):
        with (OUT / fname).open("w", encoding="utf-8-sig", newline="") as f:
            w = csv.DictWriter(f, fieldnames=list(rows[0].keys()))
            w.writeheader()
            w.writerows(rows)
    print(f"템플릿 {len(templates)}개, 단계 {len(steps)}행 (문장 틀 {len(P)}개) → {OUT}")


if __name__ == "__main__":
    main()
